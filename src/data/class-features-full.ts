/** מיזוג יכולות קיימות עם הרשימה המלאה, בלי כפילויות שם+רמה. */
export function mergeFeatures(existing: ClassFeature[] = [], full: ClassFeature[] = []): ClassFeature[] {
  const out = [...full];
  for (const f of existing) {
    if (!out.some((g) => g.level === f.level && g.name === f.name)) out.push(f);
  }
  return out.sort((a, b) => a.level - b.level || a.name.localeCompare(b.name));
}
